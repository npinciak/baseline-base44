import { jsPDF } from 'jspdf';
import { getDisplayName } from '@/lib/displayName';
import { getLevelInfo } from '@/lib/coinLevels';

export function downloadMoneyPlaybook({ user, profile, stats, chapters = [], goals = [], walletBalance = 0, lifetimeCoins = 0 }) {
  const doc = new jsPDF({ unit: 'pt', format: 'letter' });
  const name = getDisplayName(user, profile) || 'Baseline Member';
  const levelInfo = getLevelInfo(lifetimeCoins);
  const learnedCount = chapters.filter((c) => c.learned).length;
  const movesDone = chapters.filter((c) => c.move && c.moveDone);
  const nextChapter = chapters.find((c) => c.unlocked && (!c.learned || (c.move && !c.moveDone)));

  doc.setFillColor(8, 12, 22);
  doc.rect(0, 0, 612, 118, 'F');
  doc.setTextColor(46, 253, 122);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text('BASELINE · PERSONAL MONEY PLAYBOOK', 44, 42);

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(22);
  doc.text(`${name}'s Money Playbook`, 44, 70);

  doc.setTextColor(180, 195, 215);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(
    `Generated ${new Date().toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric' })}  ·  Level ${levelInfo.current.level} (${levelInfo.current.title})`,
    44,
    92
  );

  let y = 152;
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text('1. Snapshot & BaseCoin Standing', 44, y);
  y += 20;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10.5);
  const summaryLines = [
    `• BaseScore: ${stats?.base_score != null ? `${stats.base_score} / 500` : 'Complete BaseScore check to benchmark'}`,
    `• BaseCoin Level: Level ${levelInfo.current.level} · ${levelInfo.current.title} (${lifetimeCoins.toLocaleString()} Lifetime BC earned)`,
    `• Spendable Wallet Balance: ${(walletBalance ?? 0).toLocaleString()} BC  |  Current Streak: ${stats?.current_streak || 0} days`,
    `• BasePath Mastery: ${learnedCount} of ${chapters.length} chapters mastered  ·  ${movesDone.length} real-world Money Moves completed`,
  ];
  summaryLines.forEach((line) => {
    doc.text(line, 52, y);
    y += 18;
  });

  y += 14;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text('2. Completed Real-World Money Moves', 44, y);
  y += 20;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10.5);
  if (movesDone.length === 0) {
    doc.text('• Complete all lessons in Chapter 1 to unlock and log your first Money Move.', 52, y);
    y += 18;
  } else {
    movesDone.slice(0, 10).forEach((ch) => {
      doc.text(`✓ Ch ${ch.number} (${ch.title}): ${ch.move.title}`, 52, y);
      y += 17;
    });
  }

  y += 14;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text('3. Active Savings Goals', 44, y);
  y += 20;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10.5);
  if (!goals?.length) {
    doc.text('• No savings goal logged yet. Visit Money -> Savings Goals to set your emergency fund target.', 52, y);
    y += 18;
  } else {
    goals.slice(0, 5).forEach((g) => {
      const cur = Number(g.current_amount || 0).toLocaleString();
      const tgt = Number(g.target_amount || 0).toLocaleString();
      doc.text(`• ${g.name || g.title || 'Savings Goal'}: $${cur} / $${tgt}`, 52, y);
      y += 17;
    });
  }

  y += 14;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text('4. Recommended Next Focus', 44, y);
  y += 20;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10.5);
  if (nextChapter) {
    doc.text(`• Next Chapter Focus: Chapter ${nextChapter.number} — ${nextChapter.title}`, 52, y);
    y += 17;
    if (nextChapter.move && !nextChapter.moveDone) {
      doc.text(`• Target Money Move: ${nextChapter.move.title}`, 52, y);
      y += 17;
    }
  } else {
    doc.text('• You have completed every published BasePath chapter. Review the 3x Curriculum Roadmap for upcoming tracks.', 52, y);
    y += 17;
  }

  doc.setTextColor(110, 120, 135);
  doc.setFontSize(9);
  doc.text('Educational summary generated by Baseline. Not personalized investment, tax, or legal advice.', 44, 748);

  doc.save('baseline-money-playbook.pdf');
}